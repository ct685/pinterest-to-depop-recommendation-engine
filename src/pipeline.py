"""End-to-end inference pipeline for the Outfit Vibe Recommender.

This is the notebook logic (notebooks 02, 04, 05, 06-inference, 07, 08) refactored into
importable functions so the Streamlit app and any script can share one code path.

Nothing here trains anything. The usage classifier is trained in
``notebooks/06_usage_classifier.ipynb`` and only loaded for inference here. The item-pool
embeddings are built once in ``notebooks/03_item_embeddings.ipynb`` and cached to
``data/embeddings/``; this module reads that cache and never recomputes it.

Prerequisites (generated by the notebooks, git-ignored):
  data/embeddings/item_embeddings.npy   item_ids.npy   usage_classifier.pt

Run ``python -m src.pipeline`` to analyze the images in ``data/board_images/`` from the CLI.
"""

