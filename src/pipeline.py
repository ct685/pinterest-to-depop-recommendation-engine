# ---------------------------------------------------------------------------
# Model loading + embedding helpers
# ---------------------------------------------------------------------------

def get_device() -> str:
    """MPS on Apple Silicon, else CPU (the datasets here are small enough for CPU)."""
    return "mps" if torch.backends.mps.is_available() else "cpu"


def load_fashion_clip(device: str | None = None):
    """Load pretrained FashionCLIP. Returns ``(model, processor, device)``."""
    from transformers import CLIPModel, CLIPProcessor

    device = device or get_device()
    model = CLIPModel.from_pretrained(MODEL_NAME).to(device)
    model.eval()
    processor = CLIPProcessor.from_pretrained(MODEL_NAME)
    return model, processor, device


def _pooled(outputs):
    """``get_image_features`` / ``get_text_features`` return a pooled-output object on
    transformers >= 5; older versions returned a bare tensor. Handle both."""
    return getattr(outputs, "pooler_output", outputs)


def embed_images(images, model, processor, device: str) -> np.ndarray:
    """Embed PIL images (or image paths) one at a time. Returns ``(n, EMBED_DIM)``, unnormalized."""
    vectors = []
    for image in images:
        if not isinstance(image, Image.Image):
            image = Image.open(image)
        image = image.convert("RGB")
        inputs = processor(images=image, return_tensors="pt").to(device)
        with torch.no_grad():
            out = model.get_image_features(**inputs)
        vectors.append(_pooled(out)[0].cpu().numpy())
    return np.stack(vectors)


def board_vibe_vector(images, model, processor, device: str) -> np.ndarray:
    """Average every board image's embedding into one L2-normalized "vibe" vector.

    Same as notebook 02: each image is one data point describing part of the board's
    aesthetic; averaging blends them into a single summary vector.
    """
    embeddings = embed_images(images, model, processor, device)
    vibe = embeddings.mean(axis=0)
    return vibe / np.linalg.norm(vibe)


def embed_text_terms(terms, template, model, processor, device: str) -> np.ndarray:
    """Embed each term wrapped in ``template`` (CLIP prompt engineering). Rows are
    L2-normalized, so a dot product against a unit vector is the cosine similarity."""
    prompts = [template.format(term) for term in terms]
    inputs = processor(text=prompts, return_tensors="pt", padding=True).to(device)
    with torch.no_grad():
        out = model.get_text_features(**inputs)
    vecs = _pooled(out).cpu().numpy()
    return vecs / np.linalg.norm(vecs, axis=1, keepdims=True)


